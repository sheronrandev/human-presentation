#!/usr/bin/env python3
"""
scripts/lint_slop.py
Mechanical Anti-Slop Linter for PowerPoint Presentation Data.
Checks slide JSON specifications and OOXML presentations against the 66 AI Slop Rules.
Fails build if any HARD BAN (Floor Tier) violation is detected.
"""

import sys
import re
import json
from pathlib import Path

# CPY-01: Hard Banned AI Buzzwords
BUZZWORDS = [
    r"\bdelve\b", r"\btapestry\b", r"\bleverage\b", r"\bseamless(?:ly)?\b",
    r"\bpivotal\b", r"\bvibrant\b", r"\bstreamline\b", r"\bsupercharge\b",
    r"\bempower\b", r"\bgame[- ]changing\b", r"\brevolutionary\b", r"\bnext[- ]gen\b",
    r"\bcutting[- ]edge\b", r"\btransformative\b", r"\bunlock\b", r"\bunleash\b",
    r"\brobust\b", r"\bholistic\b", r"\bgroundbreaking\b", r"\bsynerg(?:y|ies)\b",
    r"\bparadigm shift\b", r"\bworld[- ]class\b", r"\bstate[- ]of[- ]the[- ]art\b",
    r"\btestament to\b", r"\bstands as\b", r"\bmarks a pivotal moment\b"
]

# CPY-07: Filler Openers
FILLER_OPENERS = [
    r"in today's (?:fast-paced|dynamic|digital) world",
    r"it's worth noting that",
    r"furthermore\b",
    r"moreover\b",
    r"let's dive in"
]

# VIS-05: Emojis and Sparkle Glyphs
EMOJIS_REGEX = re.compile(r"[\U00010000-\U0010ffff]|[\u2600-\u27bf]|[\u2300-\u23ff]|✨|🚀|💡|⚡|🎯|📌")

# CPY-05: Raw Markdown leaks
RAW_MARKDOWN_LEAKS = [
    re.compile(r"^\s*##+\s"),  # Raw ## headers
    re.compile(r"\*\*[^*]+\*\*"), # Unparsed **bold**
]

def lint_slide_data(slide, index, roadmap_allowed=False):
    violations = []
    slide_num = slide.get("slideNum", index + 1)
    title = slide.get("title", "")
    slide_type = slide.get("type", "")
    
    # Text aggregation
    all_texts = [title, slide.get("eyebrow", "")]
    if "leftText" in slide:
        all_texts.extend(slide["leftText"])
    if "rightText" in slide:
        all_texts.extend(slide["rightText"])
    if "cards" in slide:
        for c in slide["cards"]:
            all_texts.append(c.get("title", ""))
            all_texts.extend(c.get("lines", []))
    if "table" in slide:
        all_texts.extend(slide["table"].get("headers", []))
        for row in slide["table"].get("rows", []):
            all_texts.extend(row)
    if "closingLines" in slide:
        all_texts.extend(slide["closingLines"])
    
    full_slide_text = " ".join([str(t) for t in all_texts])
    
    # 1. STR-01: Unsolicited Roadmap Check
    if not roadmap_allowed:
        if re.search(r"\b(?:roadmap|timeline|agenda|schedule)\b", title, re.IGNORECASE):
            violations.append(f"STR-01 [HARD BAN]: Unsolicited Roadmap/Timeline slide detected in Slide {slide_num}: '{title}'")
            
    # 2. STR-02: Verbose Closing Fluff Check
    if slide_type == "thank_you" or re.search(r"\bthank you\b", title, re.IGNORECASE):
        fluff_matches = re.findall(r"(?:looking forward to your journey|let's transform the future together|challenges and future prospects)", full_slide_text, re.IGNORECASE)
        if fluff_matches:
            violations.append(f"STR-02 [HARD BAN]: Verbose closing fluff detected in Slide {slide_num}: '{fluff_matches[0]}'")

    # 3. CPY-01: Banned Buzzwords
    for bw in BUZZWORDS:
        matches = re.findall(bw, full_slide_text, re.IGNORECASE)
        if matches:
            violations.append(f"CPY-01 [HARD BAN]: Banned AI buzzword '{matches[0]}' detected in Slide {slide_num} ({len(matches)}x)")

    # 4. CPY-05 & VIS-05: Emojis
    emoji_matches = EMOJIS_REGEX.findall(full_slide_text)
    if emoji_matches:
        violations.append(f"VIS-05 [HARD BAN]: Emojis/sparkles {emoji_matches} detected in Slide {slide_num}")

    # 5. CPY-06: Em-Dash Overuse
    em_dash_count = full_slide_text.count("—")
    if em_dash_count > 2:
        violations.append(f"CPY-06 [FINISH]: Em-dash overuse ({em_dash_count} em-dashes) in Slide {slide_num}")

    # 6. CPY-07: Filler Openers
    for filler in FILLER_OPENERS:
        if re.search(filler, full_slide_text, re.IGNORECASE):
            violations.append(f"CPY-07 [REFLEX]: Filler transition opener '{filler}' detected in Slide {slide_num}")

    # 7. LAY-01: Title accent line signal in text
    if "---" in title or "___" in title:
        violations.append(f"LAY-01 [HARD BAN]: Title underline characters detected in Slide {slide_num}")

    # 8. STR-10: Leaked AI Watermarks / Library Strings
    ai_leaks = re.findall(r"\b(?:python-pptx|pptxgenjs|generated by (?:claude|chatgpt|gemini|gamma))\b", full_slide_text, re.IGNORECASE)
    if ai_leaks:
        violations.append(f"STR-10 [HARD BAN]: Leaked AI generator watermark '{ai_leaks[0]}' detected in Slide {slide_num}")

    # 9. Claude Signature Tell (TYP-03): Escape fonts
    if re.search(r"\b(?:Instrument Serif|Fraunces)\b", full_slide_text, re.IGNORECASE):
        violations.append(f"TYP-02 [REFLEX]: Second-wave escape font detected in Slide {slide_num}")

    return violations

def lint_deck(data_path, roadmap_opt_in=False):
    path = Path(data_path)
    if not path.exists():
        print(f"Error: {data_path} not found.")
        return 1
        
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
        
    slides = data.get("slides", [])
    if not slides:
        print("Error: No slides array found in JSON.")
        return 1

    total_violations = []
    print(f"Auditing {len(slides)} slides for AI Slop patterns against 66-rule registry...")
    
    for idx, slide in enumerate(slides):
        v = lint_slide_data(slide, idx, roadmap_allowed=roadmap_opt_in)
        if v:
            total_violations.extend(v)
            
    print("-" * 70)
    if total_violations:
        print(f"FAILED: {len(total_violations)} Slop Violations Detected:")
        for viol in total_violations:
            print(f"  • {viol}")
        return 1
    else:
        print("PASSED: 100% Clean! Zero AI Slop violations detected. Build Approved.")
        return 0

if __name__ == "__main__":
    target = sys.argv[1] if len(sys.argv) > 1 else "slides_data.json"
    roadmap_flag = "--allow-roadmap" in sys.argv
    sys.exit(lint_deck(target, roadmap_flag))
